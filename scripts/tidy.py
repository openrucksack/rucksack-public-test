#!/usr/bin/env python3
"""The rucksack tidy. Python standard library only; no network; nothing clever.

What it does, in order (the same order as skills/teach/references/tidy.md):
  1. archive memory notes older than 30 days into memory/archive/
  2. rebuild ACTIVITY.md (last 30 notes, newest first)
  3. rebuild SKILLS.md from skills/*/SKILL.md
  4. apply proposals marked "approved" to the curated files; count the rest
  5. privacy check into CHECK.md (kinds and locations, never values)
  6. budgets into CHECK.md (reported, never cut)
  7. rebuild START.md, and view.html (the dashboard)
  8. stamp last_tidy in rucksack.yaml
  9. pilot: copy notes flagged feedback into feedback/

Run from anywhere:  python3 scripts/tidy.py [path-to-rucksack]
Exit code 0 always, even when CHECK.md has findings: the findings are the report.
"""
import datetime as dt
import os
import re
import sys
from pathlib import Path

ROOT = Path(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent)
TODAY = dt.date.today()
CURATED = {"USER.md", "SOUL.md", "MEMORY.md", "FLEET.md", "HEARTBEAT.md", "LEARN.md"}
NOTE_RE = re.compile(r"^(\d{4}-\d{2}-\d{2})-(\d{4})-([a-z0-9-]+)\.md$", re.I)


COMMENT_RE = re.compile(r"<!--.*?-->", re.S)


def read(p: Path) -> str:
    return p.read_text(encoding="utf-8") if p.exists() else ""


def clean(text: str) -> str:
    """Text with HTML comments removed, for parsing. Files are never rewritten from this."""
    return COMMENT_RE.sub("", text)


def write(p: Path, s: str) -> None:
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(s.rstrip("\n") + "\n", encoding="utf-8")


def section(text: str, heading: str) -> list[str]:
    """Bullet and plain lines under a '## heading' until the next heading. Comments dropped."""
    out, on = [], False
    for line in clean(text).splitlines():
        if line.startswith("## "):
            on = line[3:].strip().lower() == heading.lower()
            continue
        if on:
            s = line.strip()
            if s and s not in ("-", "- Prefer:", "- Always:", "- Never:", "- Never goes in here:", "- Ask me first before:"):
                out.append(s)
    return out


def notes(include_archive: bool = False) -> list[tuple[dt.date, str, Path]]:
    found = []
    paths = list((ROOT / "memory").glob("*.md"))
    if include_archive:
        paths += list((ROOT / "memory" / "archive").glob("*.md"))
    for p in sorted(paths):
        m = NOTE_RE.match(p.name)
        if m:
            found.append((dt.date.fromisoformat(m.group(1)), m.group(3).lower(), p))
    return sorted(found, key=lambda t: (t[0], t[2].name), reverse=True)


def note_field(text: str, heading: str) -> list[str]:
    out, on = [], False
    for line in clean(text).splitlines():
        if re.match(r"^#{1,3}\s", line) or re.match(r"^[A-Z][a-z]+:\s*$", line):
            on = line.strip("# ").rstrip(":").strip().lower() == heading.lower()
            continue
        if on and line.strip():
            out.append(line.strip().lstrip("- ").strip())
    return out


# 1. archive
def archive() -> int:
    moved = 0
    cutoff = TODAY - dt.timedelta(days=30)
    for day, _, p in notes():
        if day < cutoff:
            dest = ROOT / "memory" / "archive" / p.name
            dest.parent.mkdir(parents=True, exist_ok=True)
            p.rename(dest)
            moved += 1
    return moved


# 2. activity
def activity() -> list[str]:
    lines = []
    for day, app, p in notes()[:30]:
        text = read(p)
        did = note_field(text, "Did")
        flags = " ".join(note_field(text, "Flags"))
        tag = ""
        for f in ("error", "issue"):
            if f in flags.lower():
                tag = f"  [{f}]"
        lines.append(f"- {day.isoformat()} {app}: {did[0] if did else '(no Did line)'}{tag}")
    body = "# Activity\n\nThe last 30 notes, newest first. Generated by the tidy from memory/.\n\n" + ("\n".join(lines) if lines else "- nothing yet")
    write(ROOT / "ACTIVITY.md", body)
    return lines


# 3. skills
def skills() -> list[str]:
    lines = []
    for sk in sorted((ROOT / "skills").glob("*/SKILL.md")):
        fm = read(sk).split("---")
        meta = fm[1] if len(fm) > 2 else ""
        name = re.search(r"^name:\s*(.+)$", meta, re.M)
        desc = re.search(r"^description:\s*(.+)$", meta, re.M)
        lines.append(f"- `{name.group(1).strip() if name else sk.parent.name}`: {desc.group(1).strip() if desc else ''}")
    write(ROOT / "SKILLS.md", "# Skills\n\nGenerated by the tidy from skills/*/SKILL.md.\n\n" + ("\n".join(lines) if lines else "- none yet"))
    return lines


# 4. proposals
def proposals() -> tuple[int, int]:
    applied = pending = 0
    for _, _, p in notes(include_archive=True):
        text = read(p)
        if "applied:" in text:
            continue
        block = note_field(text, "Proposes")
        if not block:
            continue
        did_apply = False
        for line in block:
            m = re.match(r"^approved\s+([A-Za-z.]+)\s*:\s*(.+)$", line)
            if m and m.group(1) in CURATED:
                target = ROOT / m.group(1)
                write(target, read(target) + f"\n- since {TODAY.isoformat()} [stated] {m.group(2).strip()}")
                applied += 1
                did_apply = True
            elif line.lower() != "none":
                pending += 1
        if did_apply:
            write(p, text + f"\napplied: {TODAY.isoformat()}")
    return applied, pending


