def learn_header(learn: str) -> tuple[str, str]:
    """The LEARN.md header line, and a note when the look-back is due."""
    header = next((l for l in learn.splitlines() if l.startswith("curriculum:")), "curriculum: unknown")
    due = re.search(r"next (?:look-back|reflection) due:\s*(\d{4}-\d{2}-\d{2})", header)
    try:
        is_due = bool(due) and dt.date.fromisoformat(due.group(1)) <= TODAY
    except ValueError:
        is_due = False  # an impossible date is treated as not due, never a crash
    return header, (" (look-back due now)" if is_due else "")


def first_name(user: str) -> str:
    for l in section(user, "In short"):
        bare = re.sub(r"\d{4}-\d{2}-\d{2}|\[(?:stated|observed|inferred)\]", "", l.lstrip("- ")).strip(" .,")
        name = re.split(r"[,.;:]| who | and | is ", bare, 1)[0].strip()
        return name.split()[0] if len(name.split()) > 3 else name
    return ""


