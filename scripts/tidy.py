def skill_desc(meta: str) -> str:
    """A skill's description in one plain sentence: quotes stripped, folded (> or |) values joined."""
    m = re.search(r"^description:[ \t]*(.*)$", meta, re.M)
    if not m:
        return ""
    val = m.group(1).strip()
    if val in (">", "|", ">-", "|-", ">+", "|+", ""):
        rest = meta[m.end():].splitlines()[1:]
        val = " ".join(l.strip() for l in [x for x in rest] if l.startswith((" ", "\t")) and l.strip())
        val = " ".join(val.split()) if val else ""
        cont = []
        for l in meta[m.end():].splitlines()[1:]:
            if l.startswith((" ", "\t")) and l.strip():
                cont.append(l.strip())
            elif l.strip():
                break
        val = " ".join(cont)
    val = val.strip().strip("'\"").strip()
    first = val.split(". Use when")[0].rstrip(".")
    return first + "." if first else ""


