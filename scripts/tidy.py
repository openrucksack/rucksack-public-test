def table_rows(text: str, heading: str) -> list[list[str]]:
    """Table rows under '## heading'; heading "" means the table before any ## heading."""
    rows, on = [], heading == ""
    for line in clean(text).splitlines():
        if line.startswith("## "):
            on = line[3:].strip().lower() == heading.lower()
            continue
        if on and line.strip().startswith("|"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if cells and not set("".join(cells)) <= set("-: "):
                rows.append(cells)
    return rows[1:] if rows else []


def level_of(cell: str) -> int:
    m = re.search(r"[1-5]", cell or "")
    return int(m.group(0)) if m else 0


def table_with_header(text: str) -> tuple[list[str], list[list[str]]]:
    """The first table before any ## heading: its header cells (lower case) and its rows."""
    rows = []
    for line in clean(text).splitlines():
        if line.startswith("## "):
            break
        if line.strip().startswith("|"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if cells and not set("".join(cells)) <= set("-: "):
                rows.append(cells)
    return ([c.lower() for c in rows[0]], rows[1:]) if rows else ([], [])


