# 8. stamp
def stamp() -> None:
    p = ROOT / "rucksack.yaml"
    text = read(p)
    text = re.sub(r"^last_tidy:.*$", f"last_tidy: {TODAY.isoformat()}", text, flags=re.M) if "last_tidy:" in text else text + f"\nlast_tidy: {TODAY.isoformat()}"
    write(p, text)


# 9. pilot feedback
def pilot() -> int:
    if not re.search(r"^pilot:\s*true", read(ROOT / "rucksack.yaml"), re.M):
        return 0
    n = 0
    for day, app, p in notes():
        text = read(p)
        if "feedback" in " ".join(note_field(text, "Flags")).lower() and "queued:" not in text:
            body = [f"# Progress report, {day.isoformat()}, from {app}", ""]
            for h in ("Did", "Decided", "Flags"):
                body += [f"## {h}"] + [f"- {l}" for l in note_field(text, h)] + [""]
            write(ROOT / "feedback" / f"{day.isoformat()}-{app}.md", "\n".join(body))
            write(p, text + f"\nqueued: {TODAY.isoformat()}")
            n += 1
    return n


def main() -> None:
    applied, pending = proposals()
